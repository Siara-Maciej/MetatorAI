/**
 * Writes the CLI reference of the documentation site (site/reference/cli.md) from the commander
 * program itself, so the reference can never drift from the CLI. `--check` fails when it did.
 */
import { join } from "node:path";
import { buildProgram } from "../../packages/cli/src/program.ts";

/** commander is a dependency of the CLI package, not of the repository root. */
type Command = ReturnType<typeof buildProgram>;

const OUT = join(import.meta.dir, "../../site/reference/cli.md");

function leaves(cmd: Command, prefix = ""): { name: string; cmd: Command }[] {
  return cmd.commands.flatMap((sub: Command): { name: string; cmd: Command }[] => {
    const name = `${prefix}${sub.name()}`;
    return sub.commands.length > 0 ? leaves(sub, `${name} `) : [{ name, cmd: sub }];
  });
}

/** Table text: pipes escaped; angle brackets too outside code, where Markdown would read HTML. */
const code = (text: string) => `\`${text.replaceAll("|", "\\|")}\``;
const prose = (text: string) => text.replaceAll("|", "\\|").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

export function renderCliReference(): string {
  const program = buildProgram(() => {});
  const groups = new Map<string, { name: string; cmd: Command }[]>();
  for (const leaf of leaves(program)) {
    const group = leaf.name.split(" ")[0] as string;
    groups.set(group, [...(groups.get(group) ?? []), leaf]);
  }
  const out = [
    "<!-- Generated by `bun run site:reference` from the CLI itself. Do not edit by hand. -->",
    "",
    "# CLI reference",
    "",
    "Every command prints exactly one JSON object (the envelope) on stdout. See [Output and exit codes](./output.md).",
    "",
    "Global option: `-C, --root <dir>` runs the command against another repository (default: the nearest ancestor with `.git`).",
    "",
  ];
  for (const [group, commands] of groups) {
    out.push(`## ${group}`, "");
    for (const { name, cmd } of commands) {
      out.push(`### \`metator ${name}\``, "", prose(cmd.description()), "");
      out.push("```bash", `metator ${name} ${cmd.usage()}`.trimEnd(), "```", "");
      const args = cmd.registeredArguments;
      const options = cmd.options;
      if (args.length + options.length > 0) {
        out.push("| Argument or option | Description | Default |", "|---|---|---|");
        for (const a of args) {
          const choices = a.argChoices ? ` (one of: ${a.argChoices.join(", ")})` : "";
          out.push(
            `| ${code(a.required ? `<${a.name()}>` : `[${a.name()}]`)} | ${prose(a.description + choices)} | |`,
          );
        }
        for (const o of options) {
          const choices = o.argChoices ? ` (one of: ${o.argChoices.join(", ")})` : "";
          const required = o.mandatory ? " **Required.**" : "";
          const def =
            o.defaultValue === undefined || o.defaultValue === false
              ? ""
              : code(JSON.stringify(o.defaultValue));
          out.push(`| ${code(o.flags)} | ${prose(o.description + choices)}${required} | ${def} |`);
        }
        out.push("");
      }
    }
  }
  return `${out.join("\n").trimEnd()}\n`;
}

if (import.meta.main) {
  const next = renderCliReference();
  const file = Bun.file(OUT);
  const current = (await file.exists()) ? await file.text() : "";
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error("site/reference/cli.md is stale: run `bun run site:reference`");
      process.exit(1);
    }
    console.log("site/reference/cli.md is up to date");
  } else {
    await Bun.write(OUT, next);
    console.log("wrote site/reference/cli.md");
  }
}
