import { describe, expect, test } from "bun:test";
import { AgentDocument } from "@metator/core";
import { CopilotGenerator } from "../src/copilot-generator.ts";
import { CopilotSkillGenerator } from "../src/skill-generator.ts";

const agent = (extra: Record<string, unknown>) =>
  AgentDocument.parse(
    {
      kind: "Agent",
      schemaVersion: 1,
      id: "mt-x",
      role: "worker",
      description: "Does one job, used by the coordinator only.",
      tier: "reasoning",
      capabilities: ["read", "search", "metator:graph"],
      ...extra,
    },
    "mt-x.md",
  )._unsafeUnwrap();

const BODY = "\n# Input\nRun `metator graph deps a.ts`.\n";

describe("CopilotGenerator", () => {
  test("snapshot of the generated worker (tool table, model, marker)", () => {
    const file = new CopilotGenerator().agent(agent({}), BODY, {
      source: "metator/agents/mt-x.md",
      metatorCommand: "bun run metator",
    });
    expect(file).toMatchSnapshot();
  });

  test("snapshot of a coordinator with every capability and a configured model", () => {
    const coordinator = agent({
      role: "coordinator",
      capabilities: ["read", "search", "edit", "execute", "agent", "todo", "web", "metator:run"],
      delegates: ["mt-a", "mt-b"],
    });
    const file = new CopilotGenerator().agent(coordinator, BODY, {
      source: "metator/agents/mt-x.md",
      metatorCommand: "metator",
      model: "model-x",
    });
    expect(file).toMatchSnapshot();
  });
});

describe("CopilotGenerator.hooks (.github/hooks/metator.json)", () => {
  test("one command hook per event, in the VS Code agent hooks format", () => {
    const file = new CopilotGenerator().hooks("bun run metator")._unsafeUnwrap();
    expect(file.path).toBe(".github/hooks/metator.json");
    const { hooks } = JSON.parse(file.content) as { hooks: Record<string, unknown[]> };
    expect(hooks.Stop).toEqual([{ type: "command", command: "bun run metator guard stop", timeout: 10 }]);
    expect(Object.keys(hooks)).toHaveLength(6);
  });
});

describe("CopilotSkillGenerator", () => {
  test("SKILL.md and its files under .github/skills/<name>/, marked as generated", () => {
    const skill = {
      name: "mt-find-patterns",
      description: "Use when a plan needs an exemplar. Do not use for search.",
      files: ["scripts/a.sh"],
    };
    const files = new CopilotSkillGenerator().skill(
      skill,
      "# When\nx\n",
      [{ path: "scripts/a.sh", content: "echo" }],
      { source: "metator/skills/mt-find-patterns/SKILL.md" },
    );
    expect(files.map((f) => f.path)).toEqual([
      ".github/skills/mt-find-patterns/SKILL.md",
      ".github/skills/mt-find-patterns/scripts/a.sh",
    ]);
    expect(files[0]?.content).toContain(
      "<!-- generated by metator generate from metator/skills/mt-find-patterns/SKILL.md",
    );
    expect(new CopilotSkillGenerator().owns).toBe(".github/skills/*/SKILL.md");
  });
});
