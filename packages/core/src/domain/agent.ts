import { z } from "zod";
import { defineDocument } from "./versioned.ts";

/**
 * Canonical agent (ADR-0005, ADR-0030): written once, host-neutral; host plugins generate
 * `.github/agents/*.agent.md` (Copilot) and `.claude/agents/*.md` (Claude Code) from it.
 */
export const BASIC_CAPABILITIES = ["read", "search", "edit", "execute", "agent", "todo", "web"] as const;
export type BasicCapability = (typeof BASIC_CAPABILITIES)[number];

const Capability = z.union([
  z.enum(BASIC_CAPABILITIES),
  z.string().regex(/^metator:[a-z][a-z-]*$/, "expected a capability or metator:<command group>"),
]);

export const ModelTierSchema = z.enum(["reasoning", "standard", "fast"]);
export type ModelTier = z.output<typeof ModelTierSchema>;

export const AgentSchema = z.strictObject({
  id: z.string().regex(/^[a-z][a-z0-9-]*$/, "expected a kebab-case id, e.g. mt-scout"),
  role: z.enum(["coordinator", "worker"]),
  /** When to use the agent and when not: hosts pick agents by this text. */
  description: z.string().min(20),
  tier: ModelTierSchema,
  capabilities: z.array(Capability).min(1),
  /** Agents a coordinator may start (needs the `agent` capability). */
  delegates: z.array(z.string()).default([]),
  inputs: z.array(z.string()).default([]),
  output: z
    .strictObject({
      artifact: z.string().optional(),
      schema: z.string().optional(),
      summaryLines: z.number().int().positive().default(15),
    })
    .default({ summaryLines: 15 }),
  /** Shown in the host's agent picker; defaults to true for coordinators, false for workers. */
  userInvocable: z.boolean().optional(),
});
export type Agent = z.output<typeof AgentSchema>;

export const AgentDocument = defineDocument("Agent", {
  latest: AgentSchema,
  errorCode: "INVALID_CONFIG",
  hint: "Fix the agent's front matter; `metator meta agents-schema` prints the JSON Schema.",
});

export function userInvocable(agent: Agent): boolean {
  return agent.userInvocable ?? agent.role === "coordinator";
}

/** Sections each role's body must have (English or Polish headings), from the templates. */
export const REQUIRED_SECTIONS: Readonly<Record<Agent["role"], readonly (readonly string[])[]>> = {
  coordinator: [
    ["Role", "Rola"],
    ["Rules", "Zasady bezwzględne", "Zasady"],
    ["Stages", "Etapy"],
    ["Escalation", "Eskalacja"],
    ["Final report", "Raport końcowy"],
  ],
  worker: [["Input", "Wejście"], ["Procedure", "Procedura"], ["Output", "Wyjście"], ["Stop conditions"]],
};

/** Body line budgets (principles: coordinators ≤ 200 lines, workers ≤ 150). */
export const BODY_LINES: Readonly<Record<Agent["role"], number>> = { coordinator: 200, worker: 150 };

/** Command groups an agent may run, e.g. metator:graph → "graph". */
export function metatorGroups(agent: Agent): string[] {
  return agent.capabilities.filter((c) => c.startsWith("metator:")).map((c) => c.slice("metator:".length));
}

export const GENERATED_MARKER = "<!-- generated by metator generate";

/** Marker every generated host file carries: what generated it and from where (never edit by hand). */
export function generatedMarker(source: string): string {
  return `${GENERATED_MARKER} from ${source}; kind: HostFile, schemaVersion: 1. Edit the source, not this file. -->`;
}

/** Canonical bodies say `metator …`; hosts get the repo's own command (e.g. `bun run metator …`). */
export function withMetatorCommand(body: string, command: string): string {
  return command === "metator" ? body : body.replace(/`metator(?=[ `])/g, `\`${command}`);
}

const PARTIAL = /\{\{>\s*([a-z0-9-]+)\s*\}\}/g;

/** Partial names a body includes (`{{> review-lens}}`), in order. */
export function partialsOf(body: string): string[] {
  return [...body.matchAll(PARTIAL)].map((m) => m[1] as string);
}

/** Replaces `{{> name}}` with the partial's text (ARCHITECTURE §11.3); unknown names stay visible. */
export function expandPartials(body: string, partials: ReadonlyMap<string, string>): string {
  return body.replace(PARTIAL, (whole, name: string) => partials.get(name)?.trimEnd() ?? whole);
}
