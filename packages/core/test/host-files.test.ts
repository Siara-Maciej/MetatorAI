import { describe, expect, test } from "bun:test";
import { AgentSkillsGenerator, hostAgentFile } from "@metator/core";
import { skillGeneratorContract } from "@metator/testing";

skillGeneratorContract("AgentSkillsGenerator", () => new AgentSkillsGenerator("claude", ".host/skills"));

describe("AgentSkillsGenerator", () => {
  test("owns the SKILL.md files under its root", () => {
    expect(new AgentSkillsGenerator("copilot", ".github/skills").owns).toBe(".github/skills/*/SKILL.md");
  });
});

describe("hostAgentFile", () => {
  const context = { source: "metator/agents/mt-x.md", metatorCommand: "bun run metator" };

  test("front matter, the generated marker, then the prose with the repository's command", () => {
    const file = hostAgentFile(
      ".host/agents/mt-x.md",
      { name: "mt-x", tools: ["read"] },
      "\n# Do\n`metator run status`\n",
      context,
    );
    expect(file.path).toBe(".host/agents/mt-x.md");
    expect(file.content).toBe(
      "---\nname: mt-x\ntools:\n  - read\n---\n" +
        "<!-- generated by metator generate from metator/agents/mt-x.md; kind: HostFile, schemaVersion: 1. Edit the source, not this file. -->\n" +
        "\n# Do\n`bun run metator run status`\n",
    );
  });

  test("a body without a leading blank line gets one; a note goes between the marker and the prose", () => {
    const file = hostAgentFile("a.md", { name: "a" }, "# Do\n", context, "\n> note\n");
    expect(file.content.endsWith("-->\n\n> note\n\n# Do\n")).toBe(true);
  });

  test("long front matter values stay on one line", () => {
    const description = "word ".repeat(40).trim();
    expect(hostAgentFile("a.md", { description }, "x", context).content).toContain(
      `description: ${description}\n`,
    );
  });
});
