import { describe, expect, test } from "bun:test";
import { InMemoryFileSystem } from "@metator/testing";
import { stringify } from "yaml";
import { AgentCatalog, GenerateHosts, LintAgents } from "../src/application/agents.ts";
import { DEFAULT_PATHS } from "../src/application/paths.ts";
import { type Agent, withMetatorCommand } from "../src/domain/agent.ts";
import { MetatorConfigSchema } from "../src/domain/config.ts";
import { MetatorError } from "../src/domain/errors.ts";
import { err, ok } from "../src/domain/result.ts";
import type { HostAgentContext, HostGenerator } from "../src/ports/index.ts";

const WORKER_BODY =
  "# Input\nx\n\n# Procedure\n1. `metator graph deps a.ts`\n\n# Output\nx\n\n# Stop conditions\nx\n";
const COORD_BODY = "# Role\nx\n# Rules\nx\n# Stages\nx\n# Escalation\nx\n# Final report\nx\n";

const agentFile = (id: string, extra: Record<string, unknown> = {}, body = WORKER_BODY) =>
  `---\n${stringify({
    kind: "Agent",
    schemaVersion: 1,
    id,
    role: "worker",
    description: `Agent ${id} does one well defined job.`,
    tier: "standard",
    capabilities: ["read", "metator:graph"],
    ...extra,
  })}---\n${body}`;

const COORD = { role: "coordinator", capabilities: ["read", "agent"], delegates: ["mt-a"] };

async function lint(files: Record<string, string>, prefix = "mt-") {
  const fs = new InMemoryFileSystem(files);
  const report = (
    await new LintAgents(new AgentCatalog(fs, DEFAULT_PATHS), prefix).execute()
  )._unsafeUnwrap();
  return report.problems.map((p) => `${p.agent ?? p.source}: ${p.severity}: ${p.message}`);
}

describe("LintAgents", () => {
  test("a valid worker and coordinator pass", async () => {
    expect(
      await lint({
        "metator/agents/mt-a.md": agentFile("mt-a"),
        "metator/agents/mt-boss.md": agentFile("mt-boss", COORD, COORD_BODY),
      }),
    ).toEqual([]);
  });

  test("prefix, file name, delegation rules and unknown delegates", async () => {
    const problems = await lint({
      "metator/agents/other.md": agentFile("other"),
      "metator/agents/mt-w.md": agentFile("mt-w", { delegates: ["mt-ghost"] }),
      "metator/agents/mt-c.md": agentFile("mt-c", { role: "coordinator", delegates: ["mt-w"] }, COORD_BODY),
    });
    expect(problems).toEqual([
      'mt-c: error: delegating needs the "agent" capability',
      "mt-w: error: only coordinators delegate",
      'mt-w: error: delegating needs the "agent" capability',
      'other: error: id must start with "mt-"',
      "mt-w: error: delegates to unknown agent mt-ghost",
    ]);
  });

  test("missing sections and an over-long body are errors; schema errors are reported, not thrown", async () => {
    const problems = await lint({
      "metator/agents/mt-a.md": agentFile("mt-a", {}, `# Input\n${"line\n".repeat(160)}`),
      "metator/agents/mt-b.md": "---\nkind: Agent\nschemaVersion: 1\nid: mt-b\n---\nbody",
    });
    expect(problems).toEqual([
      expect.stringContaining(
        "metator/agents/mt-b.md: error: metator/agents/mt-b.md: does not match Agent v1",
      ),
      'mt-a: error: missing section "# Procedure" or "# Procedura"',
      'mt-a: error: missing section "# Output" or "# Wyjście"',
      'mt-a: error: missing section "# Stop conditions"',
      "mt-a: error: body has 161 lines, the worker budget is 150",
    ]);
  });

  test("delegation cycles are errors", async () => {
    const problems = await lint({
      "metator/agents/mt-x.md": agentFile("mt-x", { ...COORD, delegates: ["mt-y"] }, COORD_BODY),
      "metator/agents/mt-y.md": agentFile("mt-y", { ...COORD, delegates: ["mt-x"] }, COORD_BODY),
    });
    expect(problems.filter((p) => p.includes("cycle"))).toHaveLength(1);
  });
});

class FakeGenerator implements HostGenerator {
  readonly owns = ["host/*.md"];
  constructor(readonly host: "copilot" | "claude") {}
  get hooksFile() {
    return `host/${this.host}-hooks.json`;
  }
  hooks(metatorCommand: string, existing: string | undefined) {
    if (existing === "broken") return err(new MetatorError("INVALID_CONFIG", "broken hooks file"));
    return ok({ path: this.hooksFile, content: `${metatorCommand} guard *\n` });
  }
  agent(agent: Agent, body: string, context: HostAgentContext) {
    return {
      path: `host/${this.host}-${agent.id}.md`,
      content: `<!-- generated by metator generate from ${context.source} -->\n${context.model ?? "-"}\n${withMetatorCommand(body, context.metatorCommand)}`,
    };
  }
}

describe("GenerateHosts", () => {
  const files = { "metator/agents/mt-a.md": agentFile("mt-a") };
  const gen = (config: unknown, extra: Record<string, string> = {}) => {
    const fs = new InMemoryFileSystem({ ...files, ...extra });
    const run = new GenerateHosts(
      new AgentCatalog(fs, DEFAULT_PATHS),
      [new FakeGenerator("copilot"), new FakeGenerator("claude")],
      fs,
      MetatorConfigSchema.parse(config),
    );
    return { fs, run };
  };

  test("one file per agent per configured host; models per tier; the repo's metator command", async () => {
    const w = gen({
      hosts: {
        targets: ["claude"],
        metatorCommand: "npx metator",
        models: { standard: { claude: "sonnet-x" } },
      },
    });
    expect((await w.run.execute({ check: false }))._unsafeUnwrap().written).toEqual(["host/claude-mt-a.md"]);
    expect((await w.run.execute({ check: false, hooks: true }))._unsafeUnwrap().written).toEqual([
      "host/claude-hooks.json",
    ]);
    expect((await w.fs.read("host/claude-hooks.json"))._unsafeUnwrap()).toBe("npx metator guard *\n");
    const text = (await w.fs.read("host/claude-mt-a.md"))._unsafeUnwrap();
    expect(text).toContain("sonnet-x\n");
    expect(text).toContain("`npx metator graph deps a.ts`");
  });

  test("check mode finds hand edits and never writes; orphans are reported, hand-written files ignored", async () => {
    const w = gen(
      {},
      { "host/copilot-mt-gone.md": "<!-- generated by metator generate from x -->", "host/notes.md": "mine" },
    );
    await w.run.execute({ check: false, hooks: true });
    await w.fs.write("host/claude-mt-a.md", "edited");
    await w.fs.write("host/copilot-hooks.json", "hand-edited hooks");
    const report = (await w.run.execute({ check: true, hooks: true }))._unsafeUnwrap();
    expect([report.stale, report.orphaned]).toEqual([
      ["host/claude-mt-a.md", "host/copilot-hooks.json"],
      ["host/copilot-mt-gone.md"],
    ]);
    expect((await w.fs.read("host/claude-mt-a.md"))._unsafeUnwrap()).toBe("edited");
  });

  test("a hooks file the host generator cannot merge stops generation", async () => {
    const w = gen({}, { "host/claude-hooks.json": "broken" });
    expect((await w.run.execute({ check: false, hooks: true }))._unsafeUnwrapErr().message).toBe(
      "broken hooks file",
    );
    expect((await w.run.execute({ check: false }))._unsafeUnwrap().written).toEqual([
      "host/claude-mt-a.md",
      "host/copilot-mt-a.md",
    ]);
  });

  test("an invalid agent stops generation", async () => {
    const w = gen({}, { "metator/agents/mt-bad.md": "---\nkind: Agent\nschemaVersion: 1\n---\n" });
    expect((await w.run.execute({ check: false }))._unsafeUnwrapErr().code).toBe("INVALID_CONFIG");
  });
});

describe("partials", () => {
  const withPartial = agentFile("mt-a", {}, "{{> worker-sections}}\n");
  const PARTIAL = WORKER_BODY;

  test("partials are expanded before sections and budgets are checked, and before hosts get the body", async () => {
    const files = {
      "metator/agents/mt-a.md": withPartial,
      "metator/agents/partials/worker-sections.md": PARTIAL,
    };
    expect(await lint(files)).toEqual([]);
    const fs = new InMemoryFileSystem(files);
    const gen = new GenerateHosts(
      new AgentCatalog(fs, DEFAULT_PATHS),
      [new FakeGenerator("claude")],
      fs,
      MetatorConfigSchema.parse({ hosts: { targets: ["claude"] } }),
    );
    await gen.execute({ check: false });
    expect((await fs.read("host/claude-mt-a.md"))._unsafeUnwrap()).toContain("# Stop conditions");
  });

  test("an unknown partial fails lint and stops generation", async () => {
    expect(await lint({ "metator/agents/mt-a.md": withPartial })).toContain(
      "mt-a: error: includes unknown partial worker-sections",
    );
    const fs = new InMemoryFileSystem({ "metator/agents/mt-a.md": withPartial });
    const gen = new GenerateHosts(
      new AgentCatalog(fs, DEFAULT_PATHS),
      [new FakeGenerator("claude")],
      fs,
      MetatorConfigSchema.parse({}),
    );
    expect((await gen.execute({ check: false }))._unsafeUnwrapErr().code).toBe("INVALID_CONFIG");
  });
});

describe("withMetatorCommand", () => {
  test("rewrites command spans only", () => {
    expect(
      withMetatorCommand("Run `metator gate quick` and `metator`; metator is the tool.", "bun run metator"),
    ).toBe("Run `bun run metator gate quick` and `bun run metator`; metator is the tool.");
  });
});
