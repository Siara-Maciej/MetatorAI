import { describe, expect, test } from "bun:test";
import { InMemoryFileSystem } from "@metator/testing";
import { AgentCatalog } from "../src/application/agents.ts";
import { AuditAgents } from "../src/application/audit.ts";
import { DEFAULT_PATHS } from "../src/application/paths.ts";
import { SkillCatalog } from "../src/application/skills.ts";
import { type AuditNode, auditGraph, mentionedNames } from "../src/domain/audit.ts";

const node = (id: string, extra: Partial<AuditNode> = {}): AuditNode => ({
  id,
  kind: "agent",
  source: `${id}.md`,
  origin: "host",
  entry: false,
  references: [],
  ...extra,
});
const d = (to: string) => ({ to, via: "delegates" as const });
const m = (to: string) => ({ to, via: "mentions" as const });

describe("mentionedNames", () => {
  test("known kebab-case names only, never itself", () => {
    const known = new Set(["mt-scout", "eq-logic-reviewer", "mt-judge"]);
    expect(
      mentionedNames(
        "Use mt-scout, then eq-logic-reviewer; mt-judge decides. mt-unknown no.",
        known,
        "mt-judge",
      ),
    ).toEqual(["eq-logic-reviewer", "mt-scout"]);
  });
});

describe("auditGraph", () => {
  test("cycles count delegations; mentions only make things reachable", () => {
    const audit = auditGraph([
      node("mt-o", { entry: true, references: [d("mt-a")] }),
      node("mt-a", { references: [d("mt-b")] }),
      node("mt-b", { references: [d("mt-a"), m("mt-o")] }),
      node("mt-lonely"),
      node("mt-cited"),
      node("mt-skill", { kind: "skill", entry: true, references: [m("mt-cited")] }),
    ]);
    expect(audit.cycles).toEqual([["mt-a", "mt-b"]]);
    expect(audit.dead).toEqual(["mt-lonely"]);
    expect(audit.edges).toContainEqual({ from: "mt-b", to: "mt-o", via: "mentions" });
  });

  test("delegation deeper than two levels from an entry is listed once, longest first", () => {
    const audit = auditGraph([
      node("o", { entry: true, references: [d("a"), d("x")] }),
      node("a", { references: [d("b")] }),
      node("b", { references: [d("c")] }),
      node("c"),
      node("x", { references: [d("y")] }),
      node("y"),
    ]);
    expect(audit.tooDeep).toEqual([["o", "a", "b", "c"]]);
    expect(
      auditGraph([
        node("o", { entry: true, references: [d("a")] }),
        node("a", { references: [d("b")] }),
        node("b"),
      ]).tooDeep,
    ).toEqual([]);
  });

  test("a generated copy does not shadow the canon; unknown delegates are reported", () => {
    const audit = auditGraph([
      node("mt-x", { origin: "generated", source: ".github/agents/mt-x.agent.md" }),
      node("mt-x", {
        origin: "canonical",
        source: "metator/agents/mt-x.md",
        entry: true,
        references: [d("mt-ghost")],
      }),
    ]);
    expect(audit.unknownReferences).toEqual([{ from: "mt-x", to: "mt-ghost" }]);
    expect(audit.nodes).toHaveLength(2);
    expect(audit.dead).toEqual([]);
  });
});

const AGENT = (id: string, extra = "") => `---
kind: Agent
schemaVersion: 1
id: ${id}
role: coordinator
description: Runs the workflow and delegates every stage to workers.
tier: reasoning
capabilities: [read, agent]
${extra}---
Uses mt-find-patterns for exemplars.
`;

describe("AuditAgents", () => {
  test("canonical agents and skills plus hand-written host files, with their references", async () => {
    const fs = new InMemoryFileSystem({
      "metator/agents/mt-orchestrator.md": AGENT("mt-orchestrator", "delegates: [eq-planner]\n"),
      "metator/skills/mt-find-patterns/SKILL.md":
        "---\nkind: Skill\nschemaVersion: 1\nname: mt-find-patterns\ndescription: Use when you need an exemplar. Do not use for search.\n---\n# When\n",
      ".github/agents/eq-planner.agent.md":
        "---\nname: eq-planner\nagents: [eq-old-helper]\nuser-invokable: false\n---\nPlans.\n",
      ".github/agents/eq-old-helper.agent.md":
        "---\ndescription: helper\nuser-invokable: false\n---\nHelps.\n",
      ".github/prompts/eq-feature.prompt.md": "---\nagent: eq-planner\n---\nRun eq-planner on the task.\n",
      ".github/agents/mt-orchestrator.agent.md":
        "---\nname: mt-orchestrator\n---\n<!-- generated by metator generate from x -->\n",
    });
    const audit = (
      await new AuditAgents(
        new AgentCatalog(fs, DEFAULT_PATHS),
        new SkillCatalog(fs, DEFAULT_PATHS),
        fs,
      ).execute()
    )._unsafeUnwrap();
    expect(audit.nodes.map((n) => `${n.kind}:${n.id}:${n.origin}`)).toEqual([
      "agent:eq-old-helper:host",
      "agent:eq-planner:host",
      "agent:mt-orchestrator:generated",
      "agent:mt-orchestrator:canonical",
      "prompt:eq-feature:host",
      "skill:mt-find-patterns:canonical",
    ]);
    expect(audit.edges).toEqual([
      { from: "eq-feature", to: "eq-planner", via: "mentions" },
      { from: "eq-planner", to: "eq-old-helper", via: "delegates" },
      { from: "mt-orchestrator", to: "eq-planner", via: "delegates" },
      { from: "mt-orchestrator", to: "mt-find-patterns", via: "mentions" },
    ]);
    expect([audit.dead, audit.cycles, audit.unknownReferences]).toEqual([[], [], []]);
  });
});
